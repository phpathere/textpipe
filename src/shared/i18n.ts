export type MessageKey = keyof typeof vi;
export type Translate = (key: MessageKey) => string;

export function getLanguage(): "vi" | "en" {
  const language =
    typeof chrome !== "undefined" && chrome.i18n ? chrome.i18n.getUILanguage() : navigator.language;
  return language.toLowerCase().startsWith("vi") ? "vi" : "en";
}

export function createTranslator(language = getLanguage()): Translate {
  const messages = language === "vi" ? vi : en;
  return (key) => messages[key];
}

export function getLocalizedErrorMessage(error: unknown, t: Translate): string {
  if (error instanceof AppError) {
    if (error.code === "INVALID_STORAGE_DATA") return t("invalidStorageError");
    if (error.code === "SYNC_CONFLICT") return t("conflictError");
    if (error.code === "NOTE_TOO_LARGE") return t("tooLarge");
    if (error.code === "LOCKED") return t("lockedError");
    if (error.code === "INVALID_PASSPHRASE") return t("invalidPassphrase");
    if (error.code === "PASSPHRASE_POLICY") return t("passphrasePolicy");
    if (error.code === "SETTINGS_CHANGED") return t("settingsChanged");
    if (error.code === "SYNC_QUOTA") return t("syncQuota");
    if (error.code === "EMPTY_NOTE") return t("emptyNoteError");
  }
  if (error instanceof Error && error.message) return error.message;
  return t("unknownError");
}
